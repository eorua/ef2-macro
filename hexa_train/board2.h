static int tup_load(const char *fn) {
    FILE *f = fopen(fn, "r"); if (!f) return 0;
    int n; if (fscanf(f, "%d", &n) != 1 || n < 1 || n > MAXTUP) { fclose(f); return 0; }
    for (int t = 0; t < n; t++) { if (fscanf(f, "%d", &TLEN[t]) != 1 || TLEN[t] < 1 || TLEN[t] > MAXTL) { fclose(f); return 0; }
        for (int j = 0; j < TLEN[t]; j++) if (fscanf(f, "%d", &TCELL[t][j]) != 1) { fclose(f); return 0; } }
    NB_T = n; fclose(f); return 1;
}
static void tup_save(const char *fn) {
    FILE *f = fopen(fn, "w"); if (!f) return;
    fprintf(f, "%d\n", NB_T);
    for (int t = 0; t < NB_T; t++) { fprintf(f, "%d", TLEN[t]); for (int j = 0; j < TLEN[t]; j++) fprintf(f, " %d", TCELL[t][j]); fprintf(f, "\n"); }
    fclose(f);
}
