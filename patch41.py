def backup(path):
    n = 1
    while os.path.exists("%s.bak%02d" % (path, n)):
        n += 1
    shutil.copy2(path, "%s.bak%02d" % (path, n))
    return "%s.bak%02d" % (path, n)


def main():
    if not os.path.exists(os.path.join(HERE, "preset.py")):
        print("preset.py 가 없습니다. C:\\macro 에서 실행하세요."); return 1
    files = json.loads(zlib.decompress(base64.b64decode("".join(DATA.split()))).decode())
    os.makedirs(os.path.join(HERE, "tpl"), exist_ok=True)
    for rel, b64 in files.items():
        dst = os.path.join(HERE, *rel.split("/"))
        data = base64.b64decode(b64)
        if os.path.exists(dst):
            if open(dst, "rb").read() == data:
                print("최신:", rel); continue
            if rel.endswith(".py"):
                print("백업:", backup(dst))
        open(dst, "wb").write(data)
        print("저장:", rel)
    print("완료. 먼저 py barracks.py read 로 화면 읽기를 시험해 보세요 (시험 모드는 아무것도 누르지 않음).")
    return 0


